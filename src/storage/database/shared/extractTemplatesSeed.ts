/**
 * 初始化系统默认提取模版。
 * 只补齐缺失项，不覆盖已有记录（避免把用户改过的系统模版冲掉）。
 */
export async function seedExtractTemplates() {
  try {
    let created = 0;
    for (const item of DEFAULT_EXTRACT_TEMPLATES) {
      const existing = await db
        .select()
        .from(extractTemplates)
        .where(and(isNull(extractTemplates.userId), isNull(extractTemplates.dramaId), eq(extractTemplates.kind, item.kind)))
        .limit(1);
      if (existing.length > 0) continue;
      await db.insert(extractTemplates).values({
        id: generateUUID(),
        userId: null,
        dramaId: null,
        kind: item.kind,
        name: item.name,
        template: item.template,
        isActive: 1,
        sortOrder: 0,
        createdAt: new Date().toISOString(),
        updatedAt: null,
      });
      created++;
      console.log('✓ 创建默认提取模版: ' + item.name);
    }
    if (created > 0) console.log('提取模版初始化完成，新增 ' + created + ' 条');
  } catch (error) {
    console.error('提取模版初始化失败:', error);
  }
}
