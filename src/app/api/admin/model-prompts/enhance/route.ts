// 增强的系统提示词数据
const ENHANCED_PROMPTS: Record<string, string> = {
  'idea-options-system': getIdeaOptionsEnhanced(),
  'idea-system': getIdeaEnhanced(),
  'structure-system': getStructureEnhanced(),
  'trial-read-system': getTrialReadEnhanced(),
  'chapter-stream-system': getChapterStreamEnhanced(),
  'chapter-regenerate-system': getChapterRegenerateEnhanced(),
};

export async function POST(request: NextRequest) {
  try {
    const authHeader = request.headers.get('authorization');
    const payload = getUserFromToken(authHeader);
    if (!payload || payload.role !== 'admin') {
      return NextResponse.json({ error: '未授权' }, { status: 401 });
    }

    const results: { code: string; status: string; message: string }[] = [];

    for (const [code, enhancedPrompt] of Object.entries(ENHANCED_PROMPTS)) {
      try {
        const existing = await db
          .select()
          .from(modelPrompts)
          .where(eq(modelPrompts.code, code))
          .limit(1);

        if (existing.length > 0) {
          await db
            .update(modelPrompts)
            .set({
              systemPrompt: enhancedPrompt,
              updatedAt: new Date(),
            })
            .where(eq(modelPrompts.code, code));
          results.push({
            code,
            status: 'success',
            message: `已增强 (${enhancedPrompt.length} 字)`,
          });
        } else {
          results.push({
            code,
            status: 'skipped',
            message: '提示词不存在，跳过',
          });
        }
      } catch (err: any) {
        results.push({
          code,
          status: 'error',
          message: err.message || '未知错误',
        });
      }
    }

    const injectedModules = results.filter(r => r.status === 'success').length;

    return NextResponse.json({
      success: true,
      data: {
        summary: {
          total: Object.keys(ENHANCED_PROMPTS).length,
          injected: injectedModules,
          skipped: results.filter(r => r.status === 'skipped').length,
          errors: results.filter(r => r.status === 'error').length,
        },
        results,
        knowledgeInjected: [
          '章级钩子技法（13种章尾 + 7种章首）',
          '段落级钩子技法（11种 + 组合策略）',
          '悬念编排（强度分级、多线周期、期待接力）',
          '情绪弧线设计（6种弧线）',
          '情绪驱动写作（三板斧、拉扯节奏）',
          '爽点设计体系（6种爽点、递进对抗）',
          '去AI味规则（7 Gate检测、禁用词）',
          '对话设计（7种对话模式、情绪五级递进）',
          '反转工具箱（7种反转、嵌套技巧）',
          '大纲方法论（八节点结构、五步大纲）',
          '题材写作公式（21个题材结构骨架）',
          '开头设计（3种策略、黄金三章检查）',
        ],
      },
    });
  } catch (error: any) {
    console.error('[Enhance] 增强失败:', error);
    return NextResponse.json(
      { success: false, error: error.message || '增强失败' },
      { status: 500 }
    );
  }
}

