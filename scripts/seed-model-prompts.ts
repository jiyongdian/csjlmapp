async function seed() {
  console.log('[Seed] 开始初始化模型提示词配置...');

  for (const prompt of SEED_PROMPTS) {
    try {
      // 检查是否已存在
      const existing = await db.select().from(modelPrompts).where(eq(modelPrompts.code, prompt.code)).limit(1);

      if (existing.length > 0) {
        // 已存在则更新
        await db.update(modelPrompts)
          .set({
            name: prompt.name,
            description: prompt.description,
            module: prompt.module,
            systemPrompt: prompt.systemPrompt,
            userPrompt: prompt.userPrompt,
            sortOrder: prompt.sortOrder,
            updatedAt: new Date(),
          })
          .where(eq(modelPrompts.code, prompt.code));
        console.log(`[Seed] 已更新: ${prompt.code}`);
      } else {
        // 不存在则插入
        await db.insert(modelPrompts).values({
          code: prompt.code,
          name: prompt.name,
          description: prompt.description,
          module: prompt.module,
          systemPrompt: prompt.systemPrompt,
          userPrompt: prompt.userPrompt,
          sortOrder: prompt.sortOrder,
        });
        console.log(`[Seed] 已插入: ${prompt.code}`);
      }
    } catch (error) {
      console.error(`[Seed] 处理 ${prompt.code} 失败:`, error);
    }
  }

  console.log('[Seed] 模型提示词配置初始化完成');
}

seed().catch(console.error);
